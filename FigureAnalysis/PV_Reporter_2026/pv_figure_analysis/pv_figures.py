def load_data(path: Path) -> pd.DataFrame:
    if not path.is_file():
        raise FileNotFoundError(f'Cannot find extracted measurements: {path}')
    df = pd.read_csv(path, dtype={'experiment': str, 'cell_line': str, 'enhancer': str})
    missing = REQUIRED - set(df.columns)
    if missing:
        raise ValueError(f'Missing required columns {sorted(missing)}. Expected the CORRECTED pv_figures.py per_acquisition_metrics.csv.')
    if df.empty:
        raise ValueError('The extraction CSV is empty.')
    df['acquisition'] = pd.to_numeric(df.acquisition, errors='raise').astype(int)
    if df.acquisition.duplicated().any():
        raise ValueError('Duplicate global IMS acquisition numbers; cannot treat these as independent points.')
    blocks = []
    experiment_ids = []
    for row in df.itertuples():
        exp_label = str(row.experiment).strip()
        match = re.fullmatch(r'(\d+)-4', exp_label)
        if not match:
            raise ValueError(f'Unexpected block label {exp_label!r} at IMS #{row.acquisition}. Expected, e.g., 167-4.')
        block = int(match.group(1))
        if block not in BLOCKS:
            raise ValueError(f'Block ID {block} at #{row.acquisition} absent from provided biological metadata.')
        experiment_id, expected_line, expected_enhancer = BLOCKS[block]
        observed_line = ' '.join(str(row.cell_line).strip().split())
        if observed_line != expected_line:
            raise ValueError(f'IMS #{row.acquisition}: {exp_label} mapped to {expected_line}, but extracted CSV says {observed_line!r}.')
        if str(row.enhancer).strip() != expected_enhancer:
            raise ValueError(f'IMS #{row.acquisition}: {exp_label} mapped to {expected_enhancer}, but extracted CSV says {row.enhancer!r}.')
        blocks.append(block)
        experiment_ids.append(experiment_id)
    df['block_id'] = blocks
    df['experiment_id'] = experiment_ids
    for _,_,col,enhancer,unit in METRICS:
        series = pd.to_numeric(df.loc[df.enhancer.eq(enhancer) if enhancer else slice(None),col], errors='coerce')
        if unit == '%' and ((series < 0) | (series > 100)).any():
            raise ValueError(f'{col} contains a fraction outside the permitted 0-100% range.')
        if unit != '%' and (series < 0).any():
            raise ValueError(f'{col} contains a negative density.')
    return df

def metric_data(df, metric):
    _,_,col,enhancer,_ = metric
    x = df[df.enhancer == enhancer].copy() if enhancer else df.copy()
    x['metric_value'] = pd.to_numeric(x[col], errors='coerce')
    return x

def summary_record(metric, group_type, group_name, sub):
    stem, title, col, enhancer, unit = metric
    v = sub.metric_value.to_numpy(dtype=float)
    v = v[np.isfinite(v)]
    n = len(v)
    result = dict(metric=stem, metric_label=title, group_type=group_type,
                  group=group_name, enhancer=enhancer or 'both', units=unit,
                  n=n, mean=np.mean(v) if n else np.nan,
                  median=np.median(v) if n else np.nan,
                  sd=np.std(v, ddof=1) if n>1 else np.nan,
                  min=np.min(v) if n else np.nan,
                  max=np.max(v) if n else np.nan,
                  exact_zero_values=int(np.count_nonzero(v==0)),
                  exact_100_values=int(np.count_nonzero(v==100)) if unit=='%' else '',
                  shapiro_W=np.nan, shapiro_p=np.nan,
                  shapiro_status='not tested (n<3)' if n<3 else 'calculated')
    if 3 <= n <= 5000:
        if np.all(v == v[0]):
            result['shapiro_status'] = 'not tested (all values identical)'
        else:
            try:
                with np.errstate(all='ignore'):
                    w, p = stats.shapiro(v)
                result['shapiro_W'] = float(w)
                result['shapiro_p'] = float(p)
                if n < 8:
                    result['shapiro_status'] = 'calculated; very low power (n<8)'
            except ValueError:
                result['shapiro_status'] = 'not testable'
    return result

def qq(ax, sub, unit):
    data = sub.loc[np.isfinite(sub.metric_value),['metric_value','experiment_id','acquisition']].sort_values(['metric_value','acquisition'])
    v = data.metric_value.to_numpy(dtype=float)
    n = len(v)
    if n == 0:
        ax.text(.5,.5,'No observations',transform=ax.transAxes,ha='center',va='center')
        return
    if n == 1:
        ax.scatter([0],v,c=[COLORS[data.experiment_id.iloc[0]]],s=42)
        ax.text(.04,.96,'n=1: no Q–Q shape',transform=ax.transAxes,va='top',fontsize=8)
    else:
        osm, osr = stats.probplot(v,dist='norm',fit=False)
        osm=np.asarray(osm)
        osr=np.asarray(osr)
        if np.ptp(osr) > 0:
            sl,inter=np.polyfit(osm,osr,1)
            ax.plot(osm,sl*osm+inter,color='#888888',linewidth=1,linestyle='--',zorder=1)
        for x,y,ex in zip(osm,osr,data.experiment_id):
            ax.scatter(x,y,s=37,color=COLORS[str(ex)],edgecolors='none',linewidths=0,zorder=3)
    ax.set_xlabel('Theoretical normal quantile',fontsize=8)
    ax.set_ylabel(f'Observed ({unit})',fontsize=8)
    ax.grid(alpha=.12)

def one_axis(ax, sub, unit):
    good=sub[np.isfinite(sub.metric_value)].sort_values(['experiment_id','acquisition'])
    values=good.metric_value.to_numpy(dtype=float)
    if len(values):
        for k,row in enumerate(good.itertuples()):
            # deterministic horizontal jitter, only for display
            j = ((row.acquisition * 0.6180339887498949)%1 - 0.5) * .48
            ax.scatter(j, row.metric_value, color=COLORS[str(row.experiment_id)], s=42,
                       edgecolors='none',linewidths=0,zorder=3)
    else:
        ax.text(.5,.5,'No data',transform=ax.transAxes,ha='center',va='center')
    ax.set_xlim(-.38,.38)
    ax.set_xticks([])
    ax.set_ylabel(unit,fontsize=8)
    if unit=='%':
        ax.set_ylim(-4,104)
    ax.grid(axis='y',alpha=.18)

def hist(ax,sub,unit):
    good=sub[np.isfinite(sub.metric_value)]
    v=good.metric_value.to_numpy(dtype=float)
    n=len(v)
    if n:
        if np.ptp(v)==0:
            ax.axvline(v[0],color='#888888',linewidth=2)
        else:
            bins=max(3,min(9,round(np.sqrt(n))))
            ax.hist(v,bins=bins,color='#bbbbbb',edgecolor='white',alpha=.85)
        for row in good.itertuples():
            ax.scatter(row.metric_value,-.065,marker='o',s=22,color=COLORS[str(row.experiment_id)],
                       transform=ax.get_xaxis_transform(),clip_on=False,zorder=4)
