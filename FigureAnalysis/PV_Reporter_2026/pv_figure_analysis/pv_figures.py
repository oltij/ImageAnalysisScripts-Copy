def additive_residuals(x, metric):
    """Illustrative residuals from additive linear model, not a full inferential model."""
    x=x[np.isfinite(x.metric_value)].copy()
    if len(x)<6:
        return None
    fields=['cell_line','experiment_id']
    if metric[3] is None:
        fields.append('enhancer')
    arrays=[np.ones(len(x),dtype=float)]
    for f in fields:
        codes=pd.get_dummies(x[f],drop_first=True,dtype=float)
        arrays.append(codes.to_numpy())
    X=np.column_stack(arrays)
    n,p=X.shape
    if n-p < 3:
        return None
    y=x.metric_value.to_numpy(dtype=float)
    beta,_,rank,_=np.linalg.lstsq(X,y,rcond=None)
    if rank<p:
        # non-estimability/collinearity: refuse rather than present false certainty
        return None
    z=x[['experiment_id','cell_line','acquisition']].copy()
    z['metric_value']=y-X@beta
    return z, n, p

def residual_figure(df,out):
    fig,axes=plt.subplots(2,3,figsize=(15,8.3),squeeze=False)
    rows=[]
    for i,metric in enumerate(METRICS):
        ax=axes[i//3,i%3]
        x=metric_data(df,metric)
        dat=additive_residuals(x,metric)
        if dat is None:
            ax.text(.5,.5,'Not enough estimable residual degrees of freedom',
                    transform=ax.transAxes,ha='center',va='center',fontsize=9)
            rows.append(dict(metric=metric[0],n=0,residual_shapiro_W=np.nan,residual_shapiro_p=np.nan))
        else:
            resid,n,p=dat
            qq(ax,resid,'model residual')
            v=resid.metric_value.to_numpy(dtype=float)
            if len(v)>=3 and np.ptp(v)>0:
                w,pvalue=stats.shapiro(v)
            else:
                w,pvalue=np.nan,np.nan
            rows.append(dict(metric=metric[0],n=n,model_parameters=p,residual_shapiro_W=w,residual_shapiro_p=pvalue))
        ax.set_title(metric[1],fontsize=10,fontweight='bold')
        ax.spines[['top','right']].set_visible(False)
    legend=[Line2D([0],[0],marker='o',color='none',markerfacecolor=COLORS[k],markersize=7,
                   markeredgecolor='#333333',label=k) for k in EXP_ORDER]
    fig.legend(handles=legend,title='Experiment ID',ncol=3,frameon=False,loc='lower center')
    fig.suptitle('Exploratory normal Q–Q plots of additive-model residuals\n'
                 '(cell line + experiment ID; plus enhancer for PV metrics)',fontsize=13,y=.99)
    fig.subplots_adjust(left=.07,right=.98,top=.85,bottom=.1,hspace=.45,wspace=.35)
    export_formats(fig, out, 'additive_model_residual_QQ')
    plt.close(fig)
    return rows

def jitter(experiment, acquisition, span=.16):
    # Stable image-specific jitter; does not affect the measured Y values.
    digest = hashlib.sha256(f'{experiment}/{acquisition}'.encode()).digest()
    return ((int.from_bytes(digest[:4], 'big') / 2**32) - .5) * 2 * span


def prettify(ax, ylim=(0, 105)):
    if ylim is not None:
        ax.set_ylim(*ylim)
    ax.spines[['top', 'right']].set_visible(False)
    ax.tick_params(labelsize=9)


# Explicit positions so the three groups occupy less horizontal figure width.
LINE_POSITIONS = (0.15, 0.75, 1.35)
PAIR_POSITIONS = (0.13, 0.42)


def grouped_boxplot(ax, df, value_column, colors, title, ylabel, percent=False, use_shapes=False):
    """Tukey 1.5*IQR boxes, observed whisker endpoints, all dots (including outliers).

    Q1/median/Q3 are based on one value per original IMS acquisition.
    Whiskers stop at the most extreme observed points within
    [Q1 - 1.5*IQR, Q3 + 1.5*IQR]. The dots show every observation.
    """
    valid_groups = []
    for group, pos in zip(LINE_ORDER, LINE_POSITIONS):
        v = pd.to_numeric(df.loc[df.cell_line.eq(group), value_column], errors='coerce')
        v = v[np.isfinite(v)].to_numpy(dtype=float)
        if len(v):
            valid_groups.append((group, pos, v))
    if valid_groups:
        ax.boxplot(
            [v for _, _, v in valid_groups],
            positions=[pos for _, pos, _ in valid_groups],
            widths=0.245,
            whis=1.5,                       # standard Tukey 1.5 x IQR
            patch_artist=True,
            showfliers=False,               # outliers appear once as organoid dots below
            boxprops=dict(facecolor='#FCEDEF', edgecolor='#852D40', linewidth=1.0),
            whiskerprops=dict(color='#852D40', linewidth=1.0),
            capprops=dict(color='#852D40', linewidth=1.0),
            medianprops=dict(color='#4C1425', linewidth=1.35),
            zorder=2,
        )
    for row in df.itertuples(index=False):
        y = getattr(row, value_column)
        if not np.isfinite(float(y)):
            continue
        pos = LINE_POSITIONS[LINE_ORDER.index(row.cell_line)]
        x = pos + jitter(row.experiment, row.acquisition, span=.046)
        ax.scatter(x, y, color=colors[str(row.experiment_id)], s=31,
                   marker=MARKERS[row.cell_line] if use_shapes else 'o',
                   edgecolors='none', linewidths=0, zorder=4)
    ax.set_xlim(-.12, 1.75)
    ax.set_xticks(LINE_POSITIONS, LINE_ORDER)
    ax.set_ylabel(ylabel, labelpad=3)
    ax.set_title(title, loc='left', fontweight='bold', pad=4)
    values = pd.to_numeric(df[value_column], errors='coerce')
    values = values[np.isfinite(values)]
    if percent:
        highest = max(float(values.max()) if len(values) else 80.0, 1.0)
        prettify(ax, (0, min(100.5, max(25, highest * 1.17))))
    else:
        prettify(ax, None)
        ax.set_ylim(bottom=0)


