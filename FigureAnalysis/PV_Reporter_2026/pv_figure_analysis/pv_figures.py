class AnalysisError(Exception):
    pass

def single(paths, description):
    paths = sorted(Path(p) for p in paths)
    if len(paths) != 1:
        raise AnalysisError(f'{description}: expected exactly one file, got {len(paths)}: {[str(x) for x in paths[:6]]}')
    if not paths[0].is_file() or paths[0].stat().st_size == 0:
        raise AnalysisError(f'{description}: missing or empty {paths[0]}')
    return paths[0]

def read_h5_table(path, name):
    with h5py.File(path, 'r') as h5:
        ds = h5[f'tables/{name}'][()]
        return pd.read_csv(io.BytesIO(ds.tobytes()))

def read_h5_metadata(path):
    with h5py.File(path, 'r') as h5:
        return json.loads(h5['metadata/json'][()].decode('utf-8'))

def valid_mapping(h5path, marker):
    meta = read_h5_metadata(h5path)
    a = meta['objects']['object_a_name']
    b = meta['objects']['object_b_name']
    if {a, b} != {marker, 'Hoechst'}:
        raise AnalysisError(f'Marker/nuclear H5 identity mismatch: {h5path}: {a}, {b}')
    df = read_h5_table(h5path, 'cell_id_mapping')
    marker_col = 'A_ObjectID' if a == marker else 'B_ObjectID'
    nucleus_col = 'B_ObjectID' if a == marker else 'A_ObjectID'
    for col in (marker_col, nucleus_col):
        if col not in df:
            raise AnalysisError(f'Missing {col} in {h5path}')
    if df.empty:
        return set(), set()
    mk = pd.to_numeric(df[marker_col], errors='raise').astype(int)
    nu = pd.to_numeric(df[nucleus_col], errors='raise').astype(int)
    if mk.duplicated().any() or nu.duplicated().any():
        raise AnalysisError(f'Non-one-to-one marker/nucleus assignment: {h5path}')
    return set(nu.tolist()), set(mk.tolist())

def determine_line(text, override=None):
    if override:
        if override not in LINE_ORDER:
            raise AnalysisError(f'Invalid override line {override!r}; allowed {LINE_ORDER}')
        return override
    u = text.upper()
    if re.search(r'CL[ _-]*32(?!\d)', u):
        return 'H1 CL32'
    if re.search(r'CL[ _-]*23(?!\d)', u):
        return 'H1 CL23'
    if re.search(r'(?<![A-Z0-9])H1(?![A-Z0-9])', u):
        return 'H1'
    raise AnalysisError('Cannot infer H1/H1 CL32/H1 CL23 from sample name; provide --overrides CSV')

def determine_virus(text, override=None):
    if override:
        if override not in ('BiVe3', 'BiVe4'):
            raise AnalysisError(f'Invalid override enhancer: {override}')
        return override
    s = text.lower()
    three = bool(re.search(r'(?:bip?ve3|bive3)', s))
    four = bool(re.search(r'(?:bip?ve4|bive4)', s))
    if three == four:
        raise AnalysisError('Cannot infer unique BiVe3 or BiVe4 from analysis/sample; provide --overrides CSV')
    return 'BiVe3' if three else 'BiVe4'

def get_override(path):
    if not path:
        return {}
    result = {}
    with Path(path).open(newline='') as f:
        for r in csv.DictReader(f):
            name = r['experiment'].strip()
            num = int(r['acquisition'])
            if (name, num) in result:
                raise AnalysisError(f'Duplicate override: {name}/{num}')
            result[(name, num)] = r
    return result

def data_path(batch_dir):
    prepared = batch_dir / 'prepared.json'
    if not prepared.is_file():
        raise AnalysisError(f'Missing {prepared}; run from the installed maskfix batch folder')
    cfg = json.loads(prepared.read_text())
    root = cfg.get('stage_root')
    if not root:
        raise AnalysisError('prepared.json has no stage_root')
    records = cfg.get('records')
    if not isinstance(records, list) or len(records) != 50:
        raise AnalysisError('prepared.json must contain exactly 50 indexed records')
    by_index = {}
    for record in records:
        index = int(record['index'])
        if index in by_index:
            raise AnalysisError(f'Duplicate manifest index #{index}')
        by_index[index] = record
    if set(by_index) != set(range(1,51)):
        raise AnalysisError('Manifest indices must be exactly 1–50')
    for experiment, numbers in SELECTION.items():
        for number in numbers:
            record = by_index[number]
            if record['sample'] != experiment:
                raise AnalysisError(f'Selection #{number} expected {experiment} but prepared manifest states {record["sample"]}; refusing to mix data')
            if Path(record['source']).name != record['filename']:
                raise AnalysisError(f'Selection #{number}: source path filename differs from manifest')
            expected_folder = Path(root) / record['date_dir'] / record['sample'] / f'{number:03d}'
            if Path(record['destination']).resolve() != expected_folder.resolve():
                raise AnalysisError(f'Selection #{number}: destination differs from manifest staging path')
    return Path(root), by_index

def infer_stem(pilot, analysis_dir, config):
    # Prefer the generated config's channel sources; fall back to IMS metadata and directory names.
    channel_paths = config.get('channels', {})
    names = [Path(x).name for x in channel_paths.values() if isinstance(x, str)]
    candidate = ' '.join([str(analysis_dir.name), *names])
    meta_paths = list(pilot.glob('preprocessing/*/ims_metadata.json'))
    if len(meta_paths) == 1:
        m = json.loads(meta_paths[0].read_text())
        candidate += ' ' + meta_paths[0].parent.name
        if isinstance(m.get('virus_channel'), str):
            candidate += ' ' + m['virus_channel']
        for e in m.get('files', []):
            if isinstance(e, dict):
                candidate += ' ' + str(e.get('path', ''))
    return candidate

def get_pixel_size(config):
    pixel = config.get('pixel_size_um')
    if not isinstance(pixel, dict):
        raise AnalysisError('Generated config does not have pixel_size_um')
    x = float(pixel['x']); y = float(pixel['y'])
    if not (math.isfinite(x) and math.isfinite(y) and x > 0 and y > 0):
        raise AnalysisError('Invalid pixel spacing')
    return x, y

def positive_pv_roi_pixels(pv_csv, organoid_mask):
    # The end-stage retained ROI table is exactly the object population used for marker matching.
    df = pd.read_csv(pv_csv, usecols=lambda c: c in {'ROI','CellID','X','Y'})
    id_key = 'ROI' if 'ROI' in df else 'CellID' if 'CellID' in df else None
    if id_key is None or not {'X', 'Y'}.issubset(df):
        raise AnalysisError(f'PV ROI CSV lacks ROI/CellID, X, Y: {pv_csv}')
    if df.empty:
        return 0, 0, 0
    ids = pd.to_numeric(df[id_key], errors='raise').to_numpy(dtype=np.int64)
    x = pd.to_numeric(df['X'], errors='raise').to_numpy(dtype=np.int64)
    y = pd.to_numeric(df['Y'], errors='raise').to_numpy(dtype=np.int64)
    height, width = organoid_mask.shape
    if ((x < 0)|(y < 0)|(x >= width)|(y >= height)).any():
        raise AnalysisError(f'PV pixels extend past image bounds: {pv_csv}')
    xy = np.unique(y * width + x)
    maskflat = organoid_mask.ravel()
    outside = int(np.count_nonzero(~maskflat[xy]))
    if outside:
        raise AnalysisError(f'{outside} final PV ROI pixels outside reference organoid: {pv_csv}')
    return int(xy.size), int(np.unique(ids).size), outside

def analyze_one(root, record, overrides):
    experiment = record['sample']
    number = int(record['index'])
    expected_source = Path(record['source'])
    pilot = Path(record['destination'])
    if not pilot.is_dir():
        raise AnalysisError(f'Scratch directory not available: {pilot}')
    completed = pilot / 'BATCH_COMPLETE.json'
    if not completed.is_file():
        raise AnalysisError(f'Analysis not marked complete: {completed}')
    completion = json.loads(completed.read_text())
    if completion.get('completed') is not True or completion.get('manifest_index') != number:
        raise AnalysisError(f'Invalid completion status/manifest index: {completed}')
    if completion.get('source') != str(expected_source):
        raise AnalysisError(f'Source IMS mismatch in completion marker: {completed}')
    analysis_dir = pilot / 'analysis' / expected_source.stem
    if not analysis_dir.is_dir():
        raise AnalysisError(f'Expected IMS analysis folder absent: {analysis_dir}')
    if not (analysis_dir/'run_manifest.json').is_file():
        raise AnalysisError(f'Analysis manifest missing: {analysis_dir}')
    config_path = single([pilot/'generated_configs'/f'{expected_source.stem}.stitched_pipeline.json'], 'generated stitched-pipeline config')
    config = json.loads(config_path.read_text())
    sample_info = record['filename'] + ' ' + infer_stem(pilot, analysis_dir, config)
    override = overrides.get((experiment, number), {})
    line = determine_line(sample_info, override.get('line', '').strip())
    marker_dirs = sorted(x.name for x in (analysis_dir/'03_aligned_segmentation').iterdir() if x.is_dir())
    viruses = [x for x in marker_dirs if x in {'BiVe3','BiVe4'}]
    if len(viruses) != 1:
        raise AnalysisError(f'Expected exactly one BiVe3/BiVe4 marker, got {viruses}')
    virus = determine_virus(viruses[0], override.get('enhancer', '').strip())
    if virus != record['virus']:
        raise AnalysisError(f'Enhancer segmentation {virus} disagrees with frozen IMS manifest {record["virus"]} at #{number}')
    if virus != viruses[0]:
        raise AnalysisError(f'Enhancer override inconsistent with output segmentation: {virus} vs {viruses[0]}')
    x_um, y_um = get_pixel_size(config)
    mask_path = single([analysis_dir/'03_aligned_segmentation/Hoechst/OrganoidMask.tiff'], 'Hoechst organoid mask')
    mask = np.squeeze(tifffile.imread(mask_path)) > 0
    if mask.ndim != 2:
        raise AnalysisError(f'Expected 2-D Hoechst organoid mask, got {mask.shape}')
    total_area_px = int(mask.sum())
    if total_area_px <= 0:
        raise AnalysisError('Zero organoid area')
    pv_path = single([analysis_dir/'06_final_shape_filtered/PV/PV_ROI_pixels_FILTERED.csv'], 'Final PV ROI pixels')
    pv_px, pv_objects, outside_px = positive_pv_roi_pixels(pv_path, mask)
    area_mm2 = total_area_px*x_um*y_um/1e6
    virus_h5 = single([analysis_dir/'07_nuclear_colocalization'/f'{virus}_vs_Hoechst'/'analysis.h5'], 'virus-vs-nuclear H5')
    pv_h5 = single([analysis_dir/'07_nuclear_colocalization/PV_vs_Hoechst/analysis.h5'], 'PV-vs-nuclear H5')
    vir_nuclei, vir_objs = valid_mapping(virus_h5, virus)
    pv_nuclei, nuclear_pv_objs = valid_mapping(pv_h5, 'PV')
    double_nuclei = vir_nuclei & pv_nuclei
    n_vir = len(vir_nuclei); n_pv = len(pv_nuclei); n_double = len(double_nuclei)
    direct_h5 = single([analysis_dir/'08_marker_colocalization'/f'{virus}_vs_PV'/'analysis.h5'], 'virus-vs-PV H5') if (analysis_dir/'08_marker_colocalization'/f'{virus}_vs_PV'/'analysis.h5').exists() else single([analysis_dir/'08_marker_colocalization'/f'PV_vs_{virus}'/'analysis.h5'], 'PV-vs-virus H5')
    paired = read_h5_table(direct_h5, 'stable_matching')
    direct_pairs = len(paired)
    # Optional existing QC reports should be exact equals 0 where present.
    qc_path = analysis_dir/'04_organoid_mask_qc/organoid_mask_statistics.csv'
    max_disagreement = None
    if qc_path.is_file():
        qc = pd.read_csv(qc_path)
        max_disagreement = int(pd.to_numeric(qc['organoid_mask_disagreement_pixels'], errors='raise').max())
        if max_disagreement:
            raise AnalysisError(f'Nonzero shared-mask disagreement: {max_disagreement}')
    row = dict(
        experiment=experiment, acquisition=number, acquisition_label=f'{experiment}/{number:03d}',
        date_dir=record['date_dir'], source_ims_filename=record['filename'], source_ims_path=record['source'],
        cell_line=line, enhancer=virus,
        organoid_area_pixels=total_area_px, pixel_size_x_um=x_um, pixel_size_y_um=y_um,
        organoid_area_mm2=area_mm2, pv_positive_union_pixels=pv_px,
        pv_positive_area_percent=(100*pv_px/total_area_px),
        pv_segmented_objects=pv_objects, pv_nuclear_positive_cells=n_pv,
        pv_segmented_object_density_mm2=pv_objects/area_mm2,
        pv_nuclear_positive_density_mm2=n_pv/area_mm2,
        enhancer_nuclear_positive_cells=n_vir, double_positive_nuclei=n_double,
        specificity_percent=100*n_double/n_vir if n_vir else float('nan'),
        coverage_percent=100*n_double/n_pv if n_pv else float('nan'),
        direct_pairwise_matched_cell_pairs=direct_pairs,
        direct_minus_nuclear_overlap=direct_pairs-n_double,
        zero_pv_denominator=(n_pv == 0), zero_enhancer_denominator=(n_vir == 0),
        max_mask_disagreement_pixels=max_disagreement,
        pv_roi_pixels_outside_organoid=outside_px,
        source_acquisition_dir=str(pilot),
        source_hoechst_mask=str(mask_path),
        source_pv_roi_csv=str(pv_path),
        source_pv_nuclear_h5=str(pv_h5),
        source_enhancer_nuclear_h5=str(virus_h5),
        source_direct_matching_h5=str(direct_h5),
        source_config=str(config_path),
    )
    return row

