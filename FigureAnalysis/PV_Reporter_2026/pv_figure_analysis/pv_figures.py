def write_normality_diagnostics(df, out):
    qc_out = out / 'normality_qc'
    qc_out.mkdir(parents=True, exist_ok=True)
    df.to_csv(qc_out / 'per_acquisition_metrics_with_biological_metadata.csv', index=False)
    rows = []
    for metric in METRICS:
        x = metric_data(df, metric)
        for gtype, groups, field in [
            ('all', ['All'], 'experiment_id'),
            ('cell_line', GROUP_ORDER, 'cell_line'),
            ('experiment_id', EXP_ORDER, 'experiment_id'),
        ]:
            for group in groups:
                sub = x if gtype == 'all' else x[x[field].eq(group)]
