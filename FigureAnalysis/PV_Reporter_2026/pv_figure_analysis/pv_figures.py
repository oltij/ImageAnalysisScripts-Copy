def plot_pair(ax, df, enhancer, colors, label, use_shapes=False):
    """Two compact dot-only categories; same acquisition jitter for both rates."""
    sub = df.loc[df.enhancer.eq(enhancer)]
    for row in sub.itertuples(index=False):
        delta = jitter(row.experiment, row.acquisition, span=.025)
        for x, y in ((PAIR_POSITIONS[0] + delta, row.specificity_percent),
                     (PAIR_POSITIONS[1] + delta, row.coverage_percent)):
            if pd.notna(y) and np.isfinite(float(y)):
                ax.scatter(x, y, color=colors[str(row.experiment_id)], s=31,
                           marker=MARKERS[row.cell_line] if use_shapes else 'o',
                           edgecolors='none', linewidths=0, zorder=4)
    # Mean of the organoid-level percentages for each metric, independently.
    # Draw a thick black horizontal bar atop each set of dots (no error bars).
    for position, measurement in zip(PAIR_POSITIONS, ('specificity_percent', 'coverage_percent')):
        values = pd.to_numeric(sub[measurement], errors='coerce')
        values = values[np.isfinite(values)]
        if len(values):
            mean_percent = float(values.mean())
            ax.hlines(mean_percent,
                      position - .050, position + .050,
                      colors='#000000', linewidth=3.0, zorder=6)
    ax.set_xticks(PAIR_POSITIONS, ['Spec.', 'Cov.'])
    ax.set_xlim(-.025, .67)
    ax.tick_params(axis='x', pad=1)
    ax.set_ylabel('Cells (%)', labelpad=2)
    ax.set_title(label, loc='left', fontweight='bold', pad=4)
    prettify(ax, (0, 100))


def export_formats(fig, directory, stem):
    """Raster backup at >=300 dpi; vector SVG with editable text for Illustrator."""
